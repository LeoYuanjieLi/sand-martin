@mcp.tool()
async def add_description(
    semantic_clusters: Optional[str] = None
) -> str:
    """
    Adds a consolidated descriptive annotation to the Grasshopper canvas based on logical clusters.

    Args:
        semantic_clusters: Optional JSON string of clusters: [{"name": "Label", "node_ids": ["id1", "id2"]}]
    """
    logger.info("Tool called: add_description")

    try:
        # 1. Get current canvas state
        state_json = await _make_request("GET", "/state")
        state = json.loads(state_json)
        nodes = state.get("nodes", [])

        if not nodes:
            return json.dumps({"status": "success", "message": "Canvas is empty, nothing to annotate."})

        clusters = []
        if semantic_clusters:
            try:
                clusters = json.loads(semantic_clusters)
            except Exception as e:
                logger.warning(f"Failed to parse semantic_clusters: {e}")

        # 2. Cleanup old organization artifacts
        cleanup_tasks = []
        layout_nodes = []
        for node in nodes:
            if node.get("nickname") in ["Section Label", "Canvas Description"] and node.get("type") == "GH_Scribble":
                cleanup_tasks.append(_make_request("DELETE", f"/node/{node['id']}"))
            else:
                layout_nodes.append(node)

        if cleanup_tasks:
            logger.info(f"Cleaning up {len(cleanup_tasks)} old scribbles...")
            await asyncio.gather(*cleanup_tasks)

        # 3. Create a Consolidated Master Annotation
        if clusters:
            node_map = {n["id"]: n for n in nodes}
            master_text_lines = ["SCRIPT DOCUMENTATION:"]
            described_node_ids = []

            for cluster in clusters:
                c_name = cluster.get("name", "Module")
                master_text_lines.append(f"• {c_name}")

                c_node_ids = [nid for nid in cluster.get("node_ids", []) if nid in node_map]
                described_node_ids.extend(c_node_ids)

            master_text = "\n".join(master_text_lines)

            # Place one master scribble at the top-left of the canvas, above existing objects.
            placement_nodes = layout_nodes or [node_map[nid] for nid in described_node_ids]
            if placement_nodes:
                min_x = min(node.get("x", 0) for node in placement_nodes)
                min_y = min(node.get("y", 0) for node in placement_nodes)
                estimated_height = max(120, len(master_text_lines) * 32)
                margin = 40
                await _make_request("POST", "/create", {
                    "type": "Scribble",
                    "name": "Canvas Description",
                    "canvasX": int(min_x),
                    "canvasY": int(min_y - estimated_height - margin),
                    "parameters": {"Text": master_text}
                })

        return json.dumps({
            "status": "success",
            "message": "Consolidated all notes into a single master annotation."
        })

    except Exception as e:
        logger.error(f"Error annotating canvas: {e}")
        return json.dumps({"status": "error", "message": str(e)})

@mcp.prompt()
def describe_canvas() -> str:
    """
    Instructions for adding consolidated explanatory annotations to a Grasshopper script.
    """
    return """
    You are a professional Technical Writer for Grasshopper scripts. Your goal is to add a single,
    comprehensive documentation block to the canvas that explains the script's logic in plain English.

    ### ANNOTATION STRATEGY:
    1. **ANALYZE:** Call `get_canvas_state()` to map the logic. Identify the functional "tracks" or "modules".
    2. **DOCUMENT:** For each module, write a brief bullet point (1-2 sentences) explaining its role.
       - Avoid all-caps.
       - Use a professional, technical tone.
    3. **CONSOLIDATE:** Combine all these descriptions into a single "SCRIPT DOCUMENTATION" string.
    4. **PLACE:** Call `add_description(semantic_clusters=...)` passing your cluster definitions.
       - The tool will automatically consolidate your notes into one Master Scribble placed far above the script to avoid overlaps.

    *Goal: Provide a clear, non-overlapping 'Readme' directly on the Grasshopper canvas.*
    """

