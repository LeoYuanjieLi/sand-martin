logger = logging.getLogger("sand-martin")

# Initialize FastMCP server
mcp = FastMCP(
    "sand-martin",
    instructions="""
    Securely orchestrates the Grasshopper canvas within Rhino using the Sand Martin Host.

    SECURITY & AUTHENTICATION:
    This server requires a random 32-character 'shared secret' token generated by the
    Sand Martin Host in Rhino.

    The authentication uses the 'Bearer' token format in the HTTP Authorization header:
    `Authorization: Bearer <YOUR_TOKEN>`

    Example manual verification:
    `curl -X GET http://127.0.0.1:8081/state -H "Authorization: Bearer <YOUR_TOKEN>"`

    1. If the user has not provided a token, the agent MUST first ask the user to
       copy the token from the Rhino Command History (look for 'SAND MARTIN SECURITY TOKEN').
    2. Once received, the agent should write the token to the system's temporary
       directory in a file named 'sand_martin.token' for the server to discover.
    3. If a request returns an Authentication Error or 401 Unauthorized, ask the user
       to provide the latest token from Rhino and update the file.

    WORKFLOW EXAMPLE:
    To update a slider to a specific value:
    1. Call `get_canvas_state()` to find the slider's ID.
    2. Call `get_node_details(node_id)` to see its current properties.
    3. Identify a writable property (where `"r": false`) such as 'TickValue'.
    4. Call `update_node(node_id, parameters={'TickValue': 500})` to make the change.

    SCRIPTING:
    Use `create_script_node()` for C# or Python 3 scripts. For C#, pass only the
    RunScript method body. For Python, pass top-level statements and assign outputs
    such as `a`. The tool discovers Rhino's source format and validates the component.
    """
)

# Security: Bind to explicit loopback address
HOST_URL = "http://127.0.0.1:8081"

def _get_auth_token() -> Optional[str]:
    """
    Retrieves the auth token from environment variable or temp file.
    AI Agents: You can find this token in `os.path.join(tempfile.gettempdir(), 'sand_martin.token')`
    if it is not provided in the SAND_MARTIN_TOKEN environment variable.
    """
    # 1. Check environment variable
    token = os.environ.get("SAND_MARTIN_TOKEN")
    if token:
        return token

    # 2. Check temporary file for auto-discovery
    token_path = os.path.join(tempfile.gettempdir(), "sand_martin.token")
    if os.path.exists(token_path):
        try:
            with open(token_path, "r") as f:
                return f.read().strip()
        except Exception as e:
            logger.warning(f"Failed to read token file: {e}")

    return None

async def _make_request(method: str, endpoint: str, data: Optional[Dict[str, Any]] = None) -> str:
    """Helper to make requests to the Sand Martin C# Host."""

    async def _execute_request(current_token: str):
        headers = {
            "Authorization": f"Bearer {current_token}",
            "Content-Type": "application/json"
        }
        async with httpx.AsyncClient(timeout=30.0) as client:
            url = f"{HOST_URL}{endpoint}"
            if method == "GET":
                return await client.get(url, headers=headers)
            elif method == "POST":
                return await client.post(url, json=data, headers=headers)
            elif method == "PATCH":
                return await client.patch(url, json=data, headers=headers)
            elif method == "DELETE":
                return await client.delete(url, headers=headers)
            else:
                raise ValueError(f"Unsupported method: {method}")

    # 1. Hot Discovery: Always get the latest token from disk/env
    token = _get_auth_token()
    if not token:
        msg = (
            "Authentication Error: SAND_MARTIN_TOKEN environment variable is not set and "
            "the discovery file 'sand_martin.token' was not found in the system temp directory. "
            "Please ensure the Sand Martin Server is running in Grasshopper."
        )
        logger.error(msg)
        return json.dumps({"status": "error", "message": msg})

    logger.info(f"Making {method} request to {endpoint}")

    try:
        # 2. Try the request
        response = await _execute_request(token)

        # 3. If unauthorized (401), the token might have changed (Rhino restarted).
        # Refresh and retry ONCE.
        if response.status_code == 401:
            logger.warning("Unauthorized (401). Token may have changed. Refreshing...")
            new_token = _get_auth_token()
            if new_token and new_token != token:
                logger.info("Found new token. Retrying request...")
                response = await _execute_request(new_token)
            else:
                msg = (
                    "Authentication Error: 401 Unauthorized. The security token is invalid or has expired. "
                    "Please ask the user to provide the latest 'SAND MARTIN SECURITY TOKEN' from the Rhino "
                    "Command History and write it to the 'sand_martin.token' file in the system temp directory."
                )
                logger.error(msg)
                return json.dumps({"status": "error", "message": msg})

        logger.info(f"Received response: {response.status_code}")
        response.raise_for_status()
        return response.text

    except httpx.HTTPError as e:
        msg = f"HTTP error occurred: {str(e)}"
        logger.error(msg)
        return json.dumps({"status": "error", "message": msg})
    except Exception as e:
        msg = f"An error occurred: {str(e)}"
        logger.error(msg)
        return json.dumps({"status": "error", "message": msg})

